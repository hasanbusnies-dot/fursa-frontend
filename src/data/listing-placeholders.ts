/**
 * Placeholders for a listing being created under `rootSlug` (the first node of the
 * catalog path). Unknown or missing slug ⇒ the category-neutral generic set.
 */
export function placeholdersFor(rootSlug: string | null | undefined): ListingPlaceholders {
  if (!rootSlug) return GENERIC_PLACEHOLDERS;
  return CATEGORY_PLACEHOLDERS[rootSlug] ?? GENERIC_PLACEHOLDERS;
}
